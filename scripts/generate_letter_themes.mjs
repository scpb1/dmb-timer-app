function F(template, items) {
  return items.map((x) => template.replaceAll("{x}", x));
}

function uniqueInOrder(items) {
  const seen = new Set();
  const out = [];
  for (const raw of items) {
    const title = String(raw)
      .replace(/\s+/g, " ")
      .trim()
      .replaceAll("«", '"')
      .replaceAll("»", '"');
    if (!title) continue;
    const key = title.toLocaleLowerCase("ru");
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(title);
  }
  return out;
}


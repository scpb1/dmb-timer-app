const ALLOWED_JEALOUSY = [
  "момент, когда я тебя приревновала, а ты развеял все мои сомнения",
  "как я приревновала зря, а ты не разозлился",
  "день, когда мои сомнения прошли после твоих слов",
];

function assertCatalog(titles) {
  const problems = [];
  for (const title of titles) {
    const lower = title.toLocaleLowerCase("ru");
    const allowed = ALLOWED_JEALOUSY.some((item) => lower.includes(item));
    for (const pattern of FORBIDDEN) {
      if (pattern.test(title) && !allowed) {
        problems.push(`${title}  ← ${pattern}`);
      }
    }
    for (const pattern of BAD_STYLE) {
      if (pattern.test(title)) {
        problems.push(`${title}  ← плохой тон: ${pattern}`);
      }
    }
    if (
      /(ревность|ревновал|ревную|ревнуешь|приревн)/i.test(title) &&
      !allowed &&
      !/приревновала, а ты/.test(lower)
    ) {
      problems.push(`${title}  ← ревность без «ты успокоил»`);
    }
  }
  if (problems.length) {
    console.error(problems.slice(0, 40).join("\n"));
    throw new Error(`Forbidden themes: ${problems.length}`);
  }
}

function writeTs(titles) {
  fs.mkdirSync(path.dirname(tsPath), { recursive: true });
  const mapped = titles.map((title, index) => {
    const id = LEGACY_IDS[index] ?? `letter-theme-${String(index + 1).padStart(4, "0")}`;
    return `  { id: ${JSON.stringify(id)}, title: ${JSON.stringify(title)}, sortOrder: ${index + 1} },`;
  });
  const body = [
    "import type { LetterTheme } from '@/types/diary';",
    "",
    `export const LETTER_THEMES_SEED_VERSION = ${LETTER_THEMES_SEED_VERSION};`,
    "",
    "/** Каталог тем писем девушки солдату. Сидится в таблицу letter_themes. */",
    "export const SEED_LETTER_THEMES: LetterTheme[] = [",
    ...mapped,
    "];",
    "",
  ].join("\n");
  fs.writeFileSync(tsPath, body, "utf8");
}

